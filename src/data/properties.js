const makeGallery = (mainId, ...extraIds) => {
  const ids = [mainId, ...extraIds]
  while (ids.length < 5) {
    const fill = archPool[(mainId.length + ids.length) % archPool.length]
    if (!ids.includes(fill)) ids.push(fill)
  }
  return ids.map((id) => img(id, 1600))
}

